TYPE_LABELS = {0: "Dungeon", 1: "Raid", 2: "Epic Raid"}


def place_section(ctx, pl: dict) -> list[str]:
    lines = [f"## {pl['name']}", ""]
    sprite = pl.get("summary_sprite") or pl.get("detail_sprite")
    if sprite:
        lines += [ctx["assets"].img(sprite, 96), ""]
    meta = []
    if pl.get("area_type") is not None:
        meta.append(f"**Type:** {TYPE_LABELS.get(pl['area_type'], pl['area_type'])}")
    if pl.get("level") is not None:
        meta.append(f"**Req. level:** {pl['level']}")
    if pl.get("encounter_chance_permille") is not None and pl.get("encounter_chance_permille") > 0:
        meta.append(
            f"**Encounter chance:** {pl['encounter_chance_permille'] / 10:.1f}% per room"
        )
    if meta:
        lines += [" · ".join(meta), ""]

    all_enemies = pl.get("enemies") or []
    # Filter out TutorialWolf if present
    all_enemies = [e for e in all_enemies if e.get("key") != "TutorialWolf"]

    if all_enemies:
        rows = []
        def sort_key(e):
            cp = e.get("chance_permille")
            if cp is not None:
                return (0, -cp)
            unit = ctx["enemy_by_key"].get(e["key"])
            is_boss = bool(unit and unit.get("is_boss"))
            return (1 if is_boss else 2, 0)

        for e in sorted(all_enemies, key=sort_key):
            unit = ctx["enemy_by_key"].get(e["key"])
            name = unit["name"] if unit else e["key"]
            is_boss = bool(unit and unit.get("is_boss"))
            if e.get("chance_permille") is not None:
                rate = f"{e['chance_permille'] / 10:.1f}%"
                role = "**Boss**" if is_boss else "Regular"
            else:
                rate = "Event / Scripted"
                role = "**Boss**" if is_boss else "Special Spawn"

            rows.append(
                [
                    ctx["assets"].img(unit.get("sprite") if unit else None, 36),
                    f"**{name}**",
                    rate,
                    role,
                ]
            )
        lines += [table(["", "Enemy", "Share of Encounters", "Role / Type"], rows), ""]

    if pl.get("items_mentioned"):
        lines += [
            "<details><summary>Loot & item references</summary>",
            "",
            ", ".join(pl["items_mentioned"]),
            "",
            "</details>",
            "",
        ]
    return lines


def build_places(ctx, wanted_types: set, title: str, intro: str,
                 *, full: bool = True) -> str:
    places = [
        p
        for p in ctx["places"]
        if p.get("area_type") in wanted_types
        or (None in wanted_types and p.get("area_type") is None)
    ]
    places.sort(key=lambda p: (p.get("area_type") or 9, p["name"]))
    body: list[str] = []
    for pl in places:
        body += place_section(ctx, pl)
    if not full:
        return "\n".join(body)
    return "\n".join([f"# {title}", "", intro, ""] + body)


