def load(data_dir: Path, name: str):
    return json.loads((data_dir / name).read_text(encoding="utf-8"))


def md_cell(text) -> str:
    """Make a value safe inside a markdown table cell."""
    if text is None:
        return "—"
    s = str(text)
    s = s.replace("|", "\\|").replace("\n", " ").strip()
    return s or "—"


def table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        out.append("| " + " | ".join(md_cell(c) for c in row) + " |")
    return "\n".join(out)


def write_page(wiki: Path, rel: str, body: str, generated: bool = True) -> None:
    target = wiki / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    prefix = (BANNER + "\n") if generated else ""
    target.write_text(prefix + body.rstrip() + "\n", encoding="utf-8")
    print(f"  page {rel}")


def write_marker_block(wiki: Path, rel: str, header: str, block: str) -> None:
    """Create the page with header + markers, or refresh the marker block."""
    target = wiki / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    fresh = f"{header.rstrip()}\n\n{BEGIN}\n{block.rstrip()}\n{END}\n"
    if target.is_file():
        text = target.read_text(encoding="utf-8")
        bi, ei = text.find(BEGIN), text.find(END)
        if bi == -1 or ei == -1 or ei < bi:
            print(f"  error: {rel} is missing marker comments", file=sys.stderr)
            raise SystemExit(2)
        text = text[: bi + len(BEGIN)] + "\n" + block.rstrip() + "\n" + text[ei:]
        target.write_text(text, encoding="utf-8")
    else:
        target.write_text(fresh, encoding="utf-8")
    print(f"  page {rel} (markers)")


class Assets:
    """Resolves sprite resource names to /images/<file> URLs."""

    def __init__(self, data_dir: Path):
        self.files: dict[str, str] = {}
        manifest_path = data_dir / "sprites_manifest.json"
        if not manifest_path.is_file():
            return  # export_sprites.py has not run yet; render without images
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        self.files = {
            name: entry["file"] for name, entry in manifest["exported"].items()
        }

    def img(self, sprite: str | None, size: int = 28) -> str:
        if not sprite or sprite not in self.files:
            return "—"
        return (
            f'<img :src="$withBase(\'/images/{self.files[sprite]}\')" class="sprite" '
            f'alt="{sprite}" width="{size}" height="{size}">'
        )


def fmt_stats(stats: dict) -> str:
    parts = []
    for key, val in (stats or {}).items():
        label = STAT_LABELS.get(key, key)
        if key in PERCENT_STATS and isinstance(val, (int, float)):
            pct = val * 100 if abs(val) <= 1.0 else val
            sign = "+" if pct > 0 else ""
            parts.append(f"{label} {sign}{pct:g}%")
        elif isinstance(val, (int, float)):
            sign = "+" if val > 0 and key not in ("baseMaxHp", "maxHp", "hp") else ""
            parts.append(f"{label} {sign}{val:g}" if isinstance(val, float) else f"{label} {sign}{val}")
        else:
            parts.append(f"{label} {val}")
    return " · ".join(parts) or "—"


