def build_changelog(ctx) -> str:
    lines = [
        "# Changelog",
        "",
        "Every mod release, newest first (extracted from `ModChangelog*.kt`).",
        "",
    ]
    for v in ctx["changelog"]:
        date = f" — {v['date']}" if v.get("date") else ""
        lines += [f"## v{v['version']}{date}", ""]
        for group in v.get("groups") or []:
            if not group:
                continue
            head = group[0]
            rest = group[1:]
            if head.endswith(":"):
                lines += [f"**{head}**", ""]
                if rest:
                    lines += [f"- {pt}" for pt in rest] + [""]
            else:
                lines += [f"- {pt}" for pt in group] + [""]
    return "\n".join(lines)


