def fmt_damage(expr: str | None) -> str:
    if not expr:
        return "—"
    expr = expr.strip().rstrip("{}").strip().strip("`")
    if re.fullmatch(r"-?\d+", expr):
        return expr
    return expr if len(expr) <= 60 else "…"


def build_bestiary(ctx) -> str:
    lines = [
        "# Bestiary",
        "",
        "Complete catalog of all enemies with base statistics, damage ranges, and item drop rates.",
        "Boss encounters are marked with 👑 and special independent bonus drops are marked with ★.",
        "",
    ]
    rows = []
    for e in sorted(ctx["enemies"], key=lambda x: x["name"] or x["key"]):
        drops = []
        for d in e.get("drops") or []:
            drops.append(
                f"{ctx['item_names'].get(d['item'], d['item'])} ×{d['qty']} "
                f"({d['weight'] / 10:.1f}%)"
            )
        for d in e.get("independent_drops") or []:
            drops.append(
                f"★ {ctx['item_names'].get(d['item'], d['item'])} ×{d['qty']} "
                f"({d['chance'] * 100:g}% independent)"
            )
        stats = e.get("stats") or {}
        rows.append(
            [
                ctx["assets"].img(e.get("sprite"), 28),
                f"**{e['name']}**" + (" 👑" if e.get("is_boss") else ""),
                stats.get("baseMaxHp", "—"),
                stats.get("baseConstitution", "—"),
                stats.get("baseIntelligence", "—"),
                stats.get("baseDexterity", "—"),
                stats.get("baseDefense", "—"),
                stats.get("baseMagicDefense", "—"),
                f"{fmt_damage(e.get('min_damage'))} – {fmt_damage(e.get('max_damage'))}",
                e.get("exp_given") if e.get("exp_given") is not None else "—",
                "<br>".join(drops) or "—",
            ]
        )
    lines.append(
        table(
            ["", "Enemy", "HP", "CON", "INT", "DEX", "DEF", "MDEF",
             "Damage", "EXP", "Drops"],
            rows,
        )
    )
    return "\n".join(lines)


