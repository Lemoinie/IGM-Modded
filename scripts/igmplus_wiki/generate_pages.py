def item_notes(item: dict) -> str:
    parts = []
    overrides = item.get("overrides") or {}
    if overrides.get("isMagic") == "true":
        parts.append("Magical Damage")
    if overrides.get("isRanged") == "true":
        parts.append("Ranged Attack")
    if overrides.get("damageDelta"):
        try:
            delta = float(overrides["damageDelta"])
            parts.append(f"Variance ±{int(delta * 100)}%")
        except ValueError:
            pass
    if overrides.get("alwaysHits") == "true":
        parts.append("Always Hits")
    if overrides.get("initiative") == "true":
        parts.append("Initiative")
    flags = item.get("flags") or {}
    if flags.get("isRareDrop"):
        parts.append("Rare Drop")
    if flags.get("isNotSellable"):
        parts.append("Cannot Sell")
    if flags.get("uniqueOrigin"):
        parts.append(f"Unique: {flags['uniqueOrigin']}")
    return "<br>".join(parts) or "—"


def build_items_table(ctx, categories: set[str]) -> str:
    rows = []
    for it in ctx["items"]["items"]:
        if it.get("category") not in categories:
            continue
        rows.append(
            [
                ctx["assets"].img(it.get("sprite"), 56),
                f"**{it['name']}**",
                it.get("category") or "—",
                it.get("price") if it.get("price") is not None else "—",
                it.get("rarity") if it.get("rarity") is not None else 0,
                fmt_stats(it.get("stats") or {}),
                item_notes(it),
            ]
        )
    rows.sort(key=lambda r: (r[3] if isinstance(r[3], (int, float)) else 0))
    return table(
        ["", "Name", "Type", "Price", "Rarity", "Stats", "Notes"], rows
    )


