def build_recipes(ctx) -> str:
    items = ctx["items"]["items"]
    by_key = {i["key"]: i for i in items}
    lines = [
        "# Recipes",
        "",
        "Workshop crafting recipes. Every recipe consumes the listed ingredients",
        "to produce equipment, materials, or upgraded items.",
        "",
        "::: tip Workshop Upgrades",
        "Crafting speed increases with each workshop level, reducing total craft times.",
        ":::",
        "",
        "## Recipes",
        "",
    ]
    rows = []
    for r in ctx["recipes"]:
        out_item = by_key.get(r["output_item"])
        name = out_item["name"] if out_item else r["output_item"]
        ing_parts = []
        for i in r["ingredients"]:
            it_obj = by_key.get(i["item"], {})
            it_name = it_obj.get("name", i["item"])
            it_sprite = it_obj.get("sprite")
            img_tag = ctx["assets"].img(it_sprite, 28) if it_sprite else ""
            ing_parts.append(
                f'<span class="recipe-ingredient-chip">{img_tag}<span class="ing-name">{it_name}</span><span class="ing-qty">×{i["qty"]}</span></span>'
            )
        ing = f'<div class="recipe-ingredients-wrap">{"".join(ing_parts)}</div>'
        cat_badge = f'<span class="recipe-type-badge">{out_item.get("category")}</span>' if out_item and out_item.get("category") else ''
        output_cell = (
            f'<div class="recipe-output-cell">'
            f'{ctx["assets"].img(out_item.get("sprite") if out_item else None, 52)}'
            f'<div class="recipe-output-info"><strong>{name}</strong>{cat_badge}</div>'
            f'</div>'
        )
        price_val = out_item.get("price") if out_item else None
        price_cell = f'<span class="recipe-price">🪙 {price_val}</span>' if price_val is not None else "—"
        rows.append(
            [
                output_cell,
                '<div class="recipe-arrow">➔</div>',
                ing,
                price_cell,
            ]
        )
    lines.append(table(["Output", "", "Ingredients", "Price"], rows))
    lines += ["", "## Materials", "",
              "Base crafting materials (items without equipment stats).", ""]
    mrows = []
    for it in items:
        if it.get("category") is not None:
            continue
        mrows.append(
            [
                ctx["assets"].img(it.get("sprite"), 48),
                it["name"],
                it.get("price") if it.get("price") is not None else "—",
            ]
        )
    mrows.sort(key=lambda r: (r[2] if isinstance(r[2], (int, float)) else 0))
    lines.append(table(["", "Material", "Price"], mrows))
    lines += ["", "## Consumables, Food & Upgrades", ""]
    crows = []
    for it in items:
        if it.get("category") not in CONSUMABLE_CATS:
            continue
        crows.append(
            [
                ctx["assets"].img(it.get("sprite"), 48),
                f"**{it['name']}**",
                it.get("category"),
                it.get("price") if it.get("price") is not None else "—",
                item_notes(it),
            ]
        )
    crows.sort(key=lambda r: (r[2] or "", r[1]))
    lines.append(table(["", "Name", "Type", "Price", "Notes"], crows))
    return "\n".join(lines)


